#!/usr/bin/env python3
"""Regenerate Unreal/Veyr/Source/Veyr/VeyrAudioDefaultSounds.inl from Data/dragon/sounds.json.

The packaged game has no Data/ folder next to it, so the dragon's timed sounds are compiled in as the fallback
table (the same JSON text). Run this after editing Data/dragon/sounds.json when the change must ship.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
text = (root / 'Data/dragon/sounds.json').read_text()
json.loads(text)
assert ')JSON"' not in text
out = root / 'Unreal/Veyr/Source/Veyr/VeyrAudioDefaultSounds.inl'
out.write_text('// Generated by tools/audio/embed_dragon_sounds.py from Data/dragon/sounds.json. Do not edit.\n'
               'static const char* const GVeyrDefaultSoundsJson = R"JSON(' + text + ')JSON";\n')
print('wrote', out)
