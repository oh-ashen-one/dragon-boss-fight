#!/usr/bin/env python3
"""Write the dragon sole sample table used by the runtime grounding/SoleHeights proof (A3, 2026-11-18).

Reads the shipped dragon GLB (local only, never committed) and writes a small C++ table of derived
measurements: per foot, 12 sole sample points spread over the lowest band of the foot (glTF rest
position plus up to four skin influences), and every weighted joint's rest head. The runtime fits
an affine map from these rest heads to the imported Unreal reference pose, so no axis convention is
assumed, then skins the points with the evaluated pose (linear blend, the same weights as the mesh).

python3 tools/dragon_refine/sole_points.py --glb <Dragon_Takeoff_DangleJoin_v2.glb> \
    --output Unreal/Veyr/Source/Veyr/VeyrDragonSolePoints.inl
"""
import argparse, json, struct
from pathlib import Path
import numpy as np

CT = {5121: 'u1', 5123: '<u2', 5125: '<u4', 5126: '<f4'}
NC = {'SCALAR': 1, 'VEC3': 3, 'VEC4': 4, 'MAT4': 16}
FEET = {0: ['bone_9', 'tripo::1_Left_Limb_1'], 1: ['bone_14', 'tripo::0_Left_Limb_2', 'tripo::0_Left_Limb_3'],
        2: ['tripo::1_Right_Limb_3', 'tripo::1_Right_Limb_4'], 3: ['tripo::0_Right_Limb_3', 'tripo::0_Right_Limb_4']}


def load(path):
    b = Path(path).read_bytes(); off = 12; js = binary = None
    while off < len(b):
        n, t = struct.unpack('<II', b[off:off + 8]); c = b[off + 8:off + 8 + n]; off += 8 + n
        if t == 0x4E4F534A: js = json.loads(c)
        elif t == 0x004E4942: binary = c
    return js, binary


def accessor(js, binary, i):
    a = js['accessors'][i]; v = js['bufferViews'][a['bufferView']]
    dt = np.dtype(CT[a['componentType']]); n = NC[a['type']]
    start = v.get('byteOffset', 0) + a.get('byteOffset', 0); stride = v.get('byteStride', 0)
    if stride and stride != dt.itemsize * n:
        raw = np.frombuffer(binary, np.uint8, count=stride * a['count'], offset=start).reshape(a['count'], stride)[:, :dt.itemsize * n]
        out = np.frombuffer(raw.tobytes(), dt).reshape(a['count'], n)
    else:
        out = np.frombuffer(binary, dt, count=a['count'] * n, offset=start).reshape(a['count'], n)
    return out.astype(np.float32) / np.iinfo(dt).max if a.get('normalized') else out


def ue_name(name):
    return name.replace('::', '__')


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--glb', required=True); ap.add_argument('--output', type=Path, required=True)
    ap.add_argument('--per-foot', type=int, default=12); ap.add_argument('--band', type=float, default=0.004)
    a = ap.parse_args()
    js, binary = load(a.glb)
    prim = js['meshes'][0]['primitives'][0]; skin = js['skins'][0]
    names = [js['nodes'][j]['name'] for j in skin['joints']]
    P = accessor(js, binary, prim['attributes']['POSITION']); J = accessor(js, binary, prim['attributes']['JOINTS_0'])
    W = accessor(js, binary, prim['attributes']['WEIGHTS_0'])
    ibm = accessor(js, binary, skin['inverseBindMatrices']).reshape(-1, 4, 4)
    heads = np.array([np.linalg.inv(m.T)[:3, 3] for m in ibm])
    weight_total = np.zeros(len(names))
    for k in range(4): np.add.at(weight_total, J[:, k], W[:, k])
    dominant = np.array([names[J[i, np.argmax(W[i])]] for i in range(len(P))])
    lines = ['// Generated by tools/dragon_refine/sole_points.py from the shipped dragon GLB. Derived measurements only.',
             '// glTF rest positions (metres, Y up); the runtime fits the frame to the imported reference pose.',
             'struct FVeyrSoleJointHead { const TCHAR* Bone; float X, Y, Z; };',
             'struct FVeyrSolePoint { int32 Foot; float X, Y, Z; const TCHAR* Bones[4]; float Weights[4]; };',
             'static const FVeyrSoleJointHead GVeyrSoleJointHeads[] = {']
    for n, h, t in zip(names, heads, weight_total):
        if t > 1e-3: lines.append(f'    {{TEXT("{ue_name(n)}"), {h[0]:.6f}f, {h[1]:.6f}f, {h[2]:.6f}f}},')
    lines.append('};'); lines.append('static const FVeyrSolePoint GVeyrSolePoints[] = {')
    for foot, bones in FEET.items():
        idx = np.flatnonzero(np.isin(dominant, bones))
        low = idx[P[idx, 1] <= P[idx, 1].min() + a.band]
        chosen = [low[np.argmin(P[low, 1])]]
        while len(chosen) < min(a.per_foot, len(low)):
            d = np.min(np.linalg.norm(P[low][:, None, [0, 2]] - P[chosen][None, :, [0, 2]], axis=2), axis=1)
            chosen.append(low[int(np.argmax(d))])
        for i in chosen:
            order = np.argsort(-W[i])
            bones4 = ', '.join(f'TEXT("{ue_name(names[J[i, k]])}")' if W[i, k] > 0 else 'nullptr' for k in order)
            weights4 = ', '.join(f'{W[i, k]:.6f}f' for k in order)
            lines.append(f'    {{{foot}, {P[i, 0]:.6f}f, {P[i, 1]:.6f}f, {P[i, 2]:.6f}f, {{{bones4}}}, {{{weights4}}}}},')
    lines.append('};')
    a.output.write_text('\n'.join(lines) + '\n')
    print('SOLE_POINTS', a.output, 'joints', int((weight_total > 1e-3).sum()), 'points', len(lines))


if __name__ == '__main__':
    main()
